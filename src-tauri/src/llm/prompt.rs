//! 场景化 system prompt 模板（需求文档 §5.5）：Phase 2/3 填充。

pub const TRANSLATE_TEMPLATE: &str = r#"你是翻译引擎。将用户给出的文本从 {source_lang} 翻译为 {target_lang}。
要求：1) 只输出译文，不要解释；2) 保留原文格式（换行、列表、代码块）；
3) 专业术语使用目标语言行业标准译法；
4) 仅当文本为单个词或不超过 8 字的极短词组时，给出 2 个语义的候选译法并标注「译法一/译法二」；成句文本只输出一遍译文。"#;

pub const EXPLAIN_TEMPLATE: &str = r#"你是解释引擎。请解释用户给出的内容。
要求：1) 先一句话总结；2) 判断内容类型（技术概念 / 代码 / 日常表达 / 专业术语 / 长难句）并采用对应策略结构化分点展开；
3) 必要时举例；4) 代码解释意图、关键行与潜在坑；5) 长难句先直译再拆解语法与逻辑；6) 输出 Markdown。"#;

pub const CHAT_TEMPLATE: &str =
    "你是用户的追问助手。基于原文与对话历史回答用户的追问，保持与首轮场景一致的语言与风格。";
